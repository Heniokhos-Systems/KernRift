#!/usr/bin/env python3
"""Regenerate (or --check) tests/ir_reference_citations.txt.

docs/IR_REFERENCE.md cites src/*.kr by line number, and line numbers rot: at
one audit 146 of 153 citations pointed at unrelated code while still being in
range, which reads as valid and is the most insidious form of this defect --
and the manifest was then regenerated over them, freezing the wrong lines. So
the manifest records a fingerprint of EVERY line the document cites, not just
the first number of each citation: the end of a range (`src/x.kr:100`–`120`)
and a bare follow-on number (`src/x.kr:100`/`104`, `` `100`, `104` ``) are
citations too, and used to drift unseen. (Those are shapes, not citations.)

It also refuses two shapes that cannot be right whatever the code says: a
range whose end is before its start, and a line number past the end of the
file.

After editing src/ or the doc's citations, CHECK EACH CITATION AGAINST THE
CODE (the fingerprint only says a line has not moved since it was recorded,
not that it was the right line), then:
    python3 scripts/gen-ir-reference-citations.py
tests/run_tests.sh runs it with --check.
"""
import hashlib, re, sys, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
doc = os.path.join(ROOT, "docs/IR_REFERENCE.md")
out = os.path.join(ROOT, "tests/ir_reference_citations.txt")

MAIN = re.compile(r'src/([a-z_0-9]+\.kr):(\d+)')
TAIL = re.compile(r'`?\s*(?:-|–|\.\.)\s*`?(\d+)`?')
CONT = re.compile(r'`?\s*(?:/|,|and)\s*`(\d{2,})`')

def citations(text):
    """(file, number, kind, doc line, start) for every cited line, in order."""
    res = []
    for ln, line in enumerate(text.split("\n"), 1):
        for m in MAIN.finditer(line):
            f, n = m.group(1), int(m.group(2))
            res.append((f, n, "start", ln, n))
            pos = m.end()
            t = TAIL.match(line, pos)
            if t:
                res.append((f, int(t.group(1)), "end", ln, n))
                pos = t.end()
            while True:
                c = CONT.match(line, pos)
                if not c:
                    break
                res.append((f, int(c.group(1)), "more", ln, int(c.group(1))))
                pos = c.end()
    return res

cache = {}
def src_lines(f):
    if f not in cache:
        p = os.path.join(ROOT, "src", f)
        cache[f] = open(p).read().split("\n") if os.path.exists(p) else None
    return cache[f]

problems, rows = [], {}
for f, n, kind, ln, start in citations(open(doc).read()):
    lines = src_lines(f)
    if lines is None:
        problems.append(f"IR_REFERENCE.md:{ln}: src/{f} does not exist")
        continue
    if kind == "end" and n < start:
        problems.append(f"IR_REFERENCE.md:{ln}: range src/{f}:{start}-{n} runs backwards")
    if n < 1 or n > len(lines):
        problems.append(f"IR_REFERENCE.md:{ln}: src/{f}:{n} is past the end of the file ({len(lines)} lines)")
        continue
    content = lines[n - 1].strip()
    if not content:
        problems.append(f"IR_REFERENCE.md:{ln}: src/{f}:{n} is a blank line")
        continue
    rows[(f, n)] = hashlib.sha1(content.encode()).hexdigest()[:12]

body = "\n".join(f"src/{f}:{n} {h}" for (f, n), h in sorted(rows.items(), key=lambda t: (t[0][0], t[0][1])))
header = ("# Generated by scripts/gen-ir-reference-citations.py -- do not hand-edit.\n"
          "# <citation> <sha1-12 of the stripped source line it points at>\n")

if "--check" in sys.argv:
    # The document's shape, then the manifest against the CURRENT document and
    # sources: a citation the manifest lacks, a manifest entry the document no
    # longer cites, and a line whose fingerprint changed are all reported.
    try:
        have = {}
        for raw in open(out):
            raw = raw.strip()
            if raw and not raw.startswith("#"):
                cite, h = raw.split()
                have[cite] = h
    except FileNotFoundError:
        problems.append("tests/ir_reference_citations.txt is missing")
        have = {}
    want = {f"src/{f}:{n}": h for (f, n), h in rows.items()}
    for cite in sorted(set(want) | set(have)):
        if cite not in have:
            problems.append(f"{cite} is cited but not in the manifest")
        elif cite not in want:
            problems.append(f"{cite} is in the manifest but no longer cited (or now invalid)")
        elif have[cite] != want[cite]:
            problems.append(f"{cite} moved: the line it was recorded against changed")
    for p in problems:
        print(p)
    sys.exit(1 if problems else 0)

if problems:
    for p in problems:
        print(p, file=sys.stderr)
    print("not writing the manifest: fix the citations above first", file=sys.stderr)
    sys.exit(1)
with open(out, "w") as fh:
    fh.write(header + body + "\n")
print(f"wrote {len(rows)} cited lines to {out}")
