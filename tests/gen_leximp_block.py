"""Emit the lexer / import-scanner parity block of tests/run_tests.sh.

usage: python3 tests/gen_leximp_block.py kr|mlr

KernRift and MLRift run the SAME rows (this one file, committed byte-identical
in both trees; only the compiler, the file extension and the stdlib directory
are substituted, plus the few rows marked tree-only), so a divergence between
the two front ends fails one of the suites. The block sits in run_tests.sh
between its two ANCHOR LEXIMP lines, and the row lip_block_is_generated fails
when it differs from what this script prints -- edit the rows HERE and paste
the output over the old block, never edit the block by hand.
"""
import sys

